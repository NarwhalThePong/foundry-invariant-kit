'use strict';
const fs = require('fs');
const path = require('path');
const { findContract } = require('./parse');
const { ctorArgs } = require('./args');
const { ASSET } = require('./templates/common');

const TYPES = {
  erc20: { tpl: require('./templates/erc20'), asset: false, experimental: false },
  erc4626: { tpl: require('./templates/erc4626'), asset: true, experimental: false },
  lending: { tpl: require('./templates/lending'), asset: true, experimental: true },
};

function note(type, N, warnings) {
  const props = {
    erc20: ['totalSupply equals the sum of tracked balances', 'transfers never change totalSupply', 'transfers move exactly the amount', 'no balance exceeds totalSupply', 'allowance is set and spent as expected'],
    erc4626: ['convertToShares/convertToAssets round trip never favors the user', 'previewDeposit <= shares minted (and the other previews are conservative)', 'no shares are minted for zero assets', 'deposit then redeem cannot profit', 'solvency: vault asset balance >= previewRedeem(totalSupply)', 'vault asset balance covers totalAssets', 'totalSupply equals the sum of tracked share balances'],
    lending: ['(experimental) total borrows <= total deposits', '(experimental) cash + borrows cover deposits', '(experimental) a successful borrow/withdraw leaves the account within LTV (health hook)', '(experimental) every tracked actor stays healthy (no prices/interest in the harness)', '(experimental) repay never increases debt', '(experimental) repay never credits more than the pool received', '(experimental, if liquidate exists) liquidation only succeeds on unhealthy positions'],
  }[type];
  return `# ${N} invariant scaffold (${type})

Generated by foundry-invariant-kit. This is a starting point for your own
invariant testing. It is not a guarantee of correctness or security. Passing
these properties does not mean the contract is safe; review every property,
fix the TODOs, and add properties specific to your protocol.

Files:
- \`${N}Handler.sol\`: bounded fuzz actions (bound(), vm.prank, actors, ghost variables)
- \`${N}Invariant.t.sol\`: the invariant properties${TYPES[type].asset ? `\n- \`${N}Asset.sol\`: minimal mintable mock used as the underlying asset` : ''}

Properties:
${props.map((p) => `- ${p}`).join('\n')}

Run: \`forge test --match-contract ${N}InvariantTest\`
Suggested foundry.toml: \`[invariant] runs = 64, depth = 64, fail_on_revert = false\`

Tracked holders only: sum and balance checks see the tracked actors, the test contract and the handler.
Balances or shares held at any other address are invisible to them; add those holders yourself.
${warnings.length ? `\nWarnings from generation:\n${warnings.map((w) => `- ${w}`).join('\n')}\n` : ''}`;
}

// --require-progress: an afterInvariant() hook that fails a run in which no handler
// action ever succeeded. With fail_on_revert = false, reverted calls are discarded
// silently, so a handler whose actions always revert gives a vacuous green run
// (foundry-rs/foundry#5726). The handler's calls[] counters are rolled back on revert,
// so their sum counts successful calls only.
function actionNames(handlerSrc) {
  const names = new Set();
  for (const m of handlerSrc.matchAll(/countCall\("(\w+)"\)|calls\["(\w+)"\]\+\+/g)) names.add(m[1] || m[2]);
  return [...names];
}
function addProgressCheck(testSrc, handlerSrc) {
  const names = actionNames(handlerSrc);
  if (!names.length) return testSrc;
  const sum = names.map((n) => `handler.calls("${n}")`).join('\n            + ');
  const hook = `
    /// Fails a run in which no handler action succeeded (all calls reverted and were
    /// discarded). Generated by --require-progress.
    function afterInvariant() public view {
        uint256 ok = ${sum};
        assertGt(ok, 0, "no handler action succeeded in this run: every call reverted");
    }
`;
  const i = testSrc.lastIndexOf('}');
  return testSrc.slice(0, i) + hook + testSrc.slice(i);
}

function generate({ type, contractPath, name, out = 'test/invariant', cwd = process.cwd(), force = false, ltvBps = 7500, requireProgress = false }) {
  if (!TYPES[type]) throw new Error(`unknown type "${type}" (supported: ${Object.keys(TYPES).join(', ')})`);
  if (!contractPath) throw new Error('--contract is required');
  const absContract = path.resolve(cwd, contractPath);
  if (!fs.existsSync(absContract)) throw new Error(`contract file not found: ${contractPath}`);
  const contract = findContract(fs.readFileSync(absContract, 'utf8'), name);
  const N = contract.name;
  const dir = path.resolve(cwd, out, N);
  const files = [`${N}Handler.sol`, `${N}Invariant.t.sol`, 'README.md'].concat(TYPES[type].asset ? [`${N}Asset.sol`] : []);
  if (!force && files.some((f) => fs.existsSync(path.join(dir, f)))) throw new Error(`output exists in ${path.relative(cwd, dir)}; use --force to overwrite`);
  let rel = path.relative(dir, absContract).split(path.sep).join('/');
  if (!rel.startsWith('.')) rel = './' + rel;
  const a = ctorArgs(contract, { assetExpr: TYPES[type].asset ? 'asset' : null });
  const ctx = { name: N, rel, globalImport: a.needsGlobalImport, ctorArgs: a.args, contract, ltvBps };
  const warnings = [...a.warnings];
  if (type === 'lending') {
    const d = TYPES.lending.tpl.detect(contract);
    if (d.health === 'none') warnings.unshift('account-health hook NOT CONFIGURED: no healthFactor(address), getUserAccountData(address) or collateral/debt getters found; implement collateralValue/debtValue/isHealthy in the Handler');
    else warnings.unshift(`account-health hook wired from ${d.health === 'getters' ? d.collateral + '(address)/' + d.debt + '(address)' : d.health === 'healthFactor' ? 'healthFactor(address)' : 'getUserAccountData(address)'}; values are compared 1:1 with LTV ${d.ltvGetter ? 'from pool.' + d.ltvGetter + '()' : ltvBps + ' bps'}, check this matches your protocol`);
    warnings.unshift('lending is EXPERIMENTAL: actions are inferred from names; review the account-health hook');
  }
  fs.mkdirSync(dir, { recursive: true });
  const content = {
    [`${N}Handler.sol`]: TYPES[type].tpl.handler(ctx),
    [`${N}Invariant.t.sol`]: TYPES[type].tpl.invariantTest(ctx),
    'README.md': note(type, N, warnings),
  };
  if (requireProgress) content[`${N}Invariant.t.sol`] = addProgressCheck(content[`${N}Invariant.t.sol`], content[`${N}Handler.sol`]);
  if (TYPES[type].asset) content[`${N}Asset.sol`] = ASSET(`${N}Asset`);
  for (const f of files) fs.writeFileSync(path.join(dir, f), content[f]);
  return { name: N, dir, files: files.map((f) => path.join(dir, f)), warnings };
}

module.exports = { generate, TYPES, actionNames, addProgressCheck };
